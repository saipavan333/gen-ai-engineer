// Regenerate assets/ease/diagram-fonts.js: for every SVG in assets/diagrams, its viewBox width and its
// smallest label size in drawing units, measured by headless Chrome with assets/ease/legible.js itself.
// legible.js uses the table to make a diagram scroll sideways on phones when its labels would fall under 9 px.
// usage (from the course root, with `python -m http.server 8844` running there):
//   node tools/diagram_fonts.js 8844
// Run it again whenever a diagram in assets/diagrams changes. No installs: raw CDP over Node's WebSocket.
const { spawn, execSync } = require('child_process');
const fs = require('fs'), path = require('path'), os = require('os');
const PORT = process.argv[2] || '8844';
const ROOT = path.resolve(__dirname, '..');
const CHROME = process.env.CHROME || 'C:/Program Files/Google/Chrome/Application/chrome.exe';
const sleep = ms => new Promise(r => setTimeout(r, ms));
(async () => {
  const prof = fs.mkdtempSync(path.join(process.env.PAGECHECK_TMP || os.tmpdir(), 'dfonts-'));
  const ch = spawn(CHROME, ['--headless=new', '--remote-debugging-port=9599', '--user-data-dir=' + prof, '--no-first-run', '--disable-gpu',
    '--disable-component-update', '--disable-features=OptimizationGuideModelDownloading,OptimizationHints', 'about:blank'], { stdio: 'ignore' });
  let list; for (let i = 0; i < 40 && !list; i++) { try { list = await (await fetch('http://127.0.0.1:9599/json/list')).json(); } catch (e) { await sleep(250); } }
  const ws = new WebSocket(list.find(t => t.type === 'page').webSocketDebuggerUrl); await new Promise(r => ws.onopen = r);
  let mid = 0; const pend = {};
  ws.onmessage = ev => { const m = JSON.parse(ev.data); if (m.id && pend[m.id]) { pend[m.id](m); delete pend[m.id]; } };
  const send = (method, params = {}) => new Promise(r => { const id = ++mid; pend[id] = r; ws.send(JSON.stringify({ id, method, params })); });
  await send('Page.navigate', { url: 'http://localhost:' + PORT + '/track1/01-what-is-an-llm.html' }); await sleep(2500);
  const files = fs.readdirSync(path.join(ROOT, 'assets', 'diagrams')).filter(f => f.endsWith('.svg')).sort();
  const r = await send('Runtime.evaluate', { awaitPromise: true, returnByValue: true, expression: `(async()=>{
    window.EZ_DIAGRAM_FONTS = null; const out = {};
    for (const f of ${JSON.stringify(files)}) { const d = await EZLegible.measureFile('../assets/diagrams/' + f + '?gen=' + Date.now()); if (d) out[f] = [d.vbw, +d.min.toFixed(2)]; }
    return out; })()` });
  const table = r.result.result.value;
  const n = Object.keys(table).length;
  const body = '/* Generated by tools/diagram_fonts.js: { "file.svg": [viewBox width, smallest label in drawing units] }.\n' +
    '   Read by legible.js so phone legibility also works when the course is opened from disk. */\n' +
    'window.EZ_DIAGRAM_FONTS = ' + JSON.stringify(table).replace(/\],/g, '],\n') + ';\n';
  fs.writeFileSync(path.join(ROOT, 'assets', 'ease', 'diagram-fonts.js'), body);
  console.log('measured', n, 'of', files.length, 'diagrams; smallest label', Math.min(...Object.values(table).map(v => v[1])), 'units');
  ws.close(); try { execSync('taskkill /PID ' + ch.pid + ' /T /F', { stdio: 'ignore' }); } catch (e) { ch.kill(); }
  for (let i = 0; i < 40; i++) { try { fs.rmSync(prof, { recursive: true, force: true }); break; } catch (e) { await sleep(1000); } }
  if (fs.existsSync(prof)) console.log('could not delete Chrome profile', prof);
  process.exit(n === files.length ? 0 : 1);
})().catch(e => { console.error(e); process.exit(1); });
